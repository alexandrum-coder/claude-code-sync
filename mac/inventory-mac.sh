#!/bin/bash
# ============================================================================
# inventory-mac.sh — read-only inventory of the Claude setup on the Mac.
#
#   bash mac/inventory-mac.sh              # print the inventory report
#   bash mac/inventory-mac.sh --baseline   # also rewrite windows/mac-baseline.json
#
# The report uses the same sections as windows/diagnose-windows.ps1, so the two
# can be compared line by line. Secrets are never printed: MCP servers show
# name/type/command only, env and header values are left out, and any long
# token-like string is replaced with [SECRET_REDACTED].
# ============================================================================
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BASELINE="no"
[ "${1:-}" = "--baseline" ] && BASELINE="yes"

REPO="$REPO" BASELINE="$BASELINE" python3 - <<'PY'
import json, os, re, glob, subprocess

HOME = os.path.expanduser("~")
CL = os.path.join(HOME, ".claude")
APP = os.path.join(HOME, "Library/Application Support/Claude")
REPO = os.environ["REPO"]

def red(s):
    return re.sub(r"[A-Za-z0-9_\-]{24,}", "[SECRET_REDACTED]", str(s))

def load(p):
    try:
        with open(p) as f:
            return json.load(f)
    except FileNotFoundError:
        return None

def sec(t):
    print(f"\n== {t}")

print("# Claude inventory — Mac")

sec("VERSION")
try:
    print("claude on PATH:", subprocess.run(["claude", "--version"], capture_output=True, text=True).stdout.strip())
except FileNotFoundError:
    print("claude on PATH: MISSING")

for name in ("settings.json", "settings.local.json"):
    sec(f"SETTINGS {name}")
    d = load(os.path.join(CL, name))
    if d is None:
        print("MISSING"); continue
    print("keys:", sorted(d.keys()))
    p = d.get("permissions", {})
    for k in ("defaultMode", "disableBypassPermissionsMode", "blockReadsOutsideWorkingDirectories"):
        print(f"{k}:", p.get(k, "-"))
    for k in ("ask", "deny", "allow"):
        for r in p.get(k, []):
            print(f"{k}: {red(r)}")
    print("env names:", sorted(d.get("env", {}).keys()))
    print("hooks events:", sorted(d.get("hooks", {}).keys()))

sec("MARKETPLACES")
km = load(os.path.join(CL, "plugins/known_marketplaces.json")) or {}
for n, v in sorted(km.items()):
    s = v.get("source", {})
    print(f"{n} | {s.get('source')} | {s.get('repo') or s.get('url') or s.get('path')}")

sec("PLUGINS")
ip = load(os.path.join(CL, "plugins/installed_plugins.json")) or {}
ip = ip.get("plugins", ip)
for n, v in sorted(ip.items()):
    v = v[0] if isinstance(v, list) else v
    print(f"{n} | {v.get('version')}")

sec("ENABLED")
st = load(os.path.join(CL, "settings.json")) or {}
for n, on in sorted(st.get("enabledPlugins", {}).items()):
    print(f"{n} | {on}")

sec("MCP")
cj = load(os.path.join(HOME, ".claude.json")) or {}
for n, v in sorted(cj.get("mcpServers", {}).items()):
    print(f"{n} | {v.get('type', 'stdio')} | {red(v.get('command') or v.get('url'))} | env names: {sorted(v.get('env', {}).keys())}")

sec("CLAUDE_MD")
p = os.path.join(CL, "CLAUDE.md")
if os.path.islink(p):
    print("symlink ->", os.readlink(p))
elif os.path.exists(p):
    print("file, bytes:", os.path.getsize(p))
else:
    print("MISSING")

sec("MEMORY")
for m in sorted(glob.glob(os.path.join(CL, "projects/*/memory"))):
    print(f"{os.path.basename(os.path.dirname(m))} | {len(os.listdir(m))} files")

sec("LOOSE_SKILLS")
for s in sorted(glob.glob(os.path.join(CL, "skills/*/SKILL.md"))):
    print(os.path.basename(os.path.dirname(s)))

sec("LOOSE_AGENTS")
for a in sorted(glob.glob(os.path.join(CL, "agents/*.md"))):
    print(os.path.basename(a))

sec("ACCOUNT_PLUGINS")
seen = set()
for pj in glob.glob(os.path.join(APP, "local-agent-mode-sessions/*/*/rpm/*/.claude-plugin/plugin.json")):
    d = load(pj) or {}
    seen.add(f"{d.get('name')} | {d.get('version')}")
for s in sorted(seen):
    print(s)

sec("DESKTOP_PERMISSION_PREFS")
dc = load(os.path.join(APP, "claude_desktop_config.json")) or {}
pr = dc.get("preferences", {})
for k in ("bypassPermissionsOptInByAccount", "bypassPermissionsGateByAccount"):
    for acct, val in pr.get(k, {}).items():
        print(f"{k} | {acct} | {val}")
for key, folders in pr.get("epitaxyPrefs", {}).items():
    if key.startswith("epitaxy-folder-permission-mode.") and isinstance(folders, dict):
        acct = key.split(".", 1)[1]
        for folder, mode in folders.items():
            print(f"folder-mode | {acct} | {folder} | {mode}")

if os.environ.get("BASELINE") == "yes":
    base = {
        "_comment": "Generated by mac/inventory-mac.sh --baseline. Read by windows/setup-windows.ps1. No secrets.",
        "marketplaces": [],
        "plugins": sorted(n for n, on in st.get("enabledPlugins", {}).items() if on),
        "mcp": [],
    }
    for n, v in sorted(km.items()):
        s = v.get("source", {})
        if s.get("source") == "directory":
            continue  # local paths differ per machine; obsydia is added from the clone
        base["marketplaces"].append({"name": n, "add": s.get("repo") or s.get("url")})
    out = os.path.join(REPO, "windows/mac-baseline.json")
    with open(out, "w") as f:
        json.dump(base, f, indent=2)
        f.write("\n")
    print(f"\nBaseline written: {out}")
PY
